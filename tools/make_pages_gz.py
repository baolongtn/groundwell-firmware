#!/usr/bin/env python3
"""Gzip the hub's two web pages into hub/GroundwellHub/pages_gz.h (v0.12).

  python tools/make_pages_gz.py

The dashboard (page.h) and the diagnostics page (diag_page.h) stay the files you edit. Gzipped they take about
30 KB less flash, which keeps the hub, with the node firmware inside it, within one update slot. Browsers unpack
them by themselves (Content-Encoding: gzip). The GitHub build runs this; tools/make_node_fw_h.py runs it too, so the
Arduino IDE route gets it as well. Without pages_gz.h the hub serves the plain pages. Don't commit pages_gz.h.
"""
import gzip, os, re

def body(path):
    s = open(path, encoding="utf-8").read()
    m = re.search(r'R"(\w*)\(', s)
    if not m: raise SystemExit("no raw string in " + path)
    end = s.rindex(")" + m.group(1) + '"')
    return s[m.end():end].encode("utf-8")

def arr(b):
    return "\n".join("  " + ", ".join(f"0x{x:02x}" for x in b[i:i + 20]) + "," for i in range(0, len(b), 20))

def main():
    hub = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hub", "GroundwellHub")
    out = os.path.join(hub, "pages_gz.h")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/make_pages_gz.py from page.h and diag_page.h. Don't edit; don't commit.\n")
        f.write("#pragma once\n#define GW_PAGES_GZ 1\n")
        for name, src in (("PAGE_GZ", "page.h"), ("DIAG_PAGE_GZ", "diag_page.h")):
            raw = body(os.path.join(hub, src))
            gz = gzip.compress(raw, 9, mtime=0)            # mtime 0: the same input always gives the same file
            assert gzip.decompress(gz) == raw
            f.write(f"static const uint32_t {name}_LEN = {len(gz)};\n")
            f.write(f"static const uint8_t {name}[] PROGMEM = {{\n{arr(gz)}\n}};\n")
            print(f"{src}: {len(raw)} bytes -> {len(gz)} gzipped")
    print("->", out)

if __name__ == "__main__":
    main()
