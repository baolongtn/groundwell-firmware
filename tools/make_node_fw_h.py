#!/usr/bin/env python3
"""Bundle a node firmware into the hub: writes hub/GroundwellHub/node_fw.h from the node's DFU package.

  python tools/make_node_fw_h.py <GroundwellNode.ino.zip> [node/GroundwellNode/GroundwellNode.ino] [hub/GroundwellHub/node_fw.h]

The .zip comes from the node build (Arduino IDE: Sketch > Export Compiled Binary, or the GitHub build).
The version is read from FW_VERSION in the node sketch. The hub then updates every node to this firmware.
"""
import json, re, sys, zipfile, os

def crc16(data):   # the bootloader's crc16_compute()
    crc = 0xFFFF
    for b in data:
        crc = ((crc >> 8) | (crc << 8)) & 0xFFFF
        crc ^= b
        crc ^= (crc & 0xFF) >> 4
        crc ^= (crc << 12) & 0xFFFF
        crc ^= ((crc & 0xFF) << 5) & 0xFFFF
    return crc

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    zpath = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
    ino = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "node", "GroundwellNode", "GroundwellNode.ino")
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, "..", "hub", "GroundwellHub", "node_fw.h")
    with zipfile.ZipFile(zpath) as z:
        app = json.loads(z.read("manifest.json"))["manifest"]["application"]
        binb, dat = z.read(app["bin_file"]), z.read(app["dat_file"])
    m = re.search(r'FW_VERSION\s*=\s*"([^"]+)"', open(ino, encoding="utf-8").read())
    if not m: sys.exit("FW_VERSION not found in " + ino)
    ver = m.group(1)
    if len(binb) % 4: sys.exit(f"node image is {len(binb)} bytes, not a multiple of 4: the bootloader would refuse it")
    if len(dat) < 2 or (dat[-2] | dat[-1] << 8) != crc16(binb):
        sys.exit("the init packet's CRC doesn't match the image: rebuild the node .zip")
    def arr(b):
        return "\n".join("  " + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + "," for i in range(0, len(b), 16))
    with open(out, "w", newline="\n") as f:
        f.write(f"// Generated by tools/make_node_fw_h.py from {os.path.basename(zpath)}. Don't edit; don't commit.\n")
        f.write("#pragma once\n#define NODE_FW_BUNDLED 1\n")
        f.write(f'static const char NODE_FW_VERSION[] = "{ver}";\n')
        f.write(f"static const uint32_t NODE_FW_LEN = {len(binb)};\n")
        f.write(f"static const uint16_t NODE_FW_DAT_LEN = {len(dat)};\n")
        f.write(f"static const uint8_t NODE_FW_DAT[] = {{\n{arr(dat)}\n}};\n")
        f.write(f"static const uint8_t NODE_FW_BIN[] = {{\n{arr(binb)}\n}};\n")
    print(f"node firmware {ver}: {len(binb)} bytes, init packet {len(dat)} bytes, CRC ok -> {out}")

main()
