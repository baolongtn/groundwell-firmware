static int countEv(const char *needle) { int n = 0; for (auto &e : events) if (e.find(needle) != std::string::npos) n++; return n; }
static BTHomePacket pkt(uint8_t pid, bool moist, int counts, uint16_t c0 = 2000, uint16_t c1 = 400) {
  BTHomePacket p; memset(&p, 0, sizeof p);
  p.hasPid = true; p.pid = pid; p.hasVolt = true; p.volt = 3.0f;
  if (moist) { p.hasMoist = true; p.moist = 45.0f; }
  p.nCounts = counts; p.counts[0] = c0; p.counts[1] = c1;
  return p;
}
static const char *A = "AA:BB:CC:DD:EE:01", *B = "AA:BB:CC:DD:EE:02", *C = "AA:BB:CC:DD:EE:03", *H = "11:22:33:44:55:66";

int main() {
  // 1. 300 readings 30 s apart, through the 255 -> 0 wrap: no restart, nothing lost, no extra check.
  for (int k = 1; k <= 300; k++) {
    fakeMs += 30000;
    handlePacket(A, -70, 1, true, pkt((uint8_t)k, true, 0));
    if (k == 2) { int i = findNode(A, false); nodes[i].nextCheckAt = 123456789; }   // a check scheduled for later
  }
  int a = findNode(A, false);
  CHECK(a >= 0);
  CHECK(nodes[a].restarts == 0);
  CHECK(nodes[a].lost == 0);
  CHECK(nodes[a].rx == 300);
  CHECK(nodes[a].nextCheckAt == 123456789);              // v0.11 reset this to 0 at every wrap
  CHECK(countEv("restarted") == 0);
  CHECK(nodes[a].dtN == 16);
  // dts hold 10 ms units: all 3000
  bool allSame = true; for (int k = 0; k < 16; k++) allSame &= nodes[a].dts[k] == 3000; CHECK(allSame);

  // 2. A real restart: id 100 -> 1.
  for (int k = 90; k <= 100; k++) { fakeMs += 30000; handlePacket(B, -60, 1, true, pkt((uint8_t)k, true, 0)); }
  int b = findNode(B, false);
  nodes[b].nextCheckAt = 999999;
  fakeMs += 30000; handlePacket(B, -60, 1, true, pkt(1, true, 0));
  CHECK(nodes[b].restarts == 1);
  CHECK(nodes[b].nextCheckAt == 0);
  CHECK(nodes[b].lost == 0);                              // a restart isn't counted as lost readings
  CHECK(countEv("restarted") == 1);

  // 3. Dropped readings: ids 2, 3, then 7 (4, 5, 6 lost), also counted in the hour window.
  fakeMs += 30000; handlePacket(B, -60, 1, true, pkt(2, true, 0));
  fakeMs += 30000; handlePacket(B, -60, 1, true, pkt(3, true, 0));
  fakeMs += 120000; handlePacket(B, -60, 1, true, pkt(7, true, 0));
  CHECK(nodes[b].lost == 3);
  long hl = 0; for (int k = 0; k < H_SLOTS; k++) hl += nodes[b].hLost[k]; CHECK(hl == 3);

  // 4. Repeats inside a burst: not new readings, but they count as copies heard.
  uint32_t rx0 = nodes[b].rx, adv0 = nodes[b].adv;
  for (int k = 0; k < 10; k++) { fakeMs += 250; handlePacket(B, -61, 1, true, pkt(7, true, 0)); }
  CHECK(nodes[b].rx == rx0 && nodes[b].adv == adv0 + 10);
  CHECK(nodes[b].windowAt == 0);                          // still inside its 6 s burst
  // ... and still advertising 9 s after the reading: its link window is open (it was just reset).
  nodes[b].nextCheckAt = 555;
  fakeMs += 6500; handlePacket(B, -61, 1, true, pkt(7, true, 0));
  CHECK(nodes[b].windowAt != 0 && nodes[b].nextCheckAt == 0);
  CHECK(countEv("link window") == 1);
  fakeMs += 1000; handlePacket(B, -61, 1, true, pkt(7, true, 0));
  CHECK(countEv("link window") == 1);                     // once per window, not every advert
  // A broadcast-only test node (not connectable) never triggers it.
  fakeMs += 30000; handlePacket(C, -50, 0, false, pkt(1, true, 0));
  fakeMs += 9000;  handlePacket(C, -50, 0, false, pkt(1, true, 0));
  CHECK(nodes[findNode(C, false)].windowAt == 0);

  // 5. A v0.11 node (moisture + rod count) updated to 0.12 (moisture only): the rod card goes away.
  int c = findNode(C, false);
  fakeMs += 30000; handlePacket(C, -50, 0, false, pkt(2, true, 1));
  CHECK(findSensor(c, 0, false) >= 0 && findSensor(c, 1, false) >= 0);
  fakeMs += 30000; handlePacket(C, -50, 0, false, pkt(3, true, 0));
  CHECK(findSensor(c, 0, false) >= 0 && findSensor(c, 1, false) < 0);
  CHECK(countEv("no longer sends probe 1") == 1);
  // an uncalibrated 0.12 node: one raw count on channel 0, nothing on channel 1
  fakeMs += 30000; handlePacket(C, -50, 0, false, pkt(4, false, 1, 2873));
  int s0 = findSensor(c, 0, false);
  CHECK(s0 >= 0 && !sensors[s0].fcal && sensors[s0].raw == 2873 && findSensor(c, 1, false) < 0);

  // 6. The hub's own sensors: same path, not Bluetooth traffic.
  uint32_t at0 = advTotal, ah0 = advHeard, fr0 = freshTotal;
  fakeMs += 30000; handlePacket(H, 0, 0, false, pkt(1, true, 0), true);
  fakeMs += 30000; handlePacket(H, 0, 0, false, pkt(2, true, 0), true);
  int h = findNode(H, false);
  CHECK(h >= 0 && nodes[h].local && nodes[h].rx == 2);
  CHECK(!strcmp(nodes[h].fw, "0.12.0") && !strcmp(nodes[h].st, "wired to this hub"));
  CHECK(advTotal == at0 && advHeard == ah0 && freshTotal == fr0);
  long ha = 0; for (int k = 0; k < H_SLOTS; k++) ha += nodes[h].hAdv[k]; CHECK(ha == 0);   // no "copies heard" for a wired node
  CHECK(findSensor(h, 0, false) >= 0 && sensors[findSensor(h, 0, false)].fcal);
  CHECK(countEv("Sensors wired to this hub: first reading") == 1);

  // 7. The hour window: 12 rotations clear what node A did an hour ago.
  long hr = 0; for (int k = 0; k < H_SLOTS; k++) hr += nodes[a].hRx[k]; CHECK(hr == 300);
  for (int k = 0; k < H_SLOTS; k++) { fakeMs += H_SLOT_MS; rotateHealthSlot(); }
  hr = 0; for (int k = 0; k < H_SLOTS; k++) hr += nodes[a].hRx[k]; CHECK(hr == 0);
  CHECK(hSlots == H_SLOTS);
  CHECK(nodes[a].rx == 300);                              // the since-start counters stay

  printf(fails ? "%d FAILURES\n" : "ALL PASS\n", fails);
  return fails ? 1 : 0;
}
