// against stand-ins for the ESP32 libraries. Covers the packet id wrap (not a restart), real restarts, dropped
// readings, link-window detection, a probe a node stops sending, readings from the hub's own sensors, the gap
// ring and the hour window.
// Run from the tools folder:
//   python3 hub_packet_test_extract.py && g++ -std=c++17 -Wall -Wno-unused-function -o hubpkt hub_packet_test.cpp && ./hubpkt
